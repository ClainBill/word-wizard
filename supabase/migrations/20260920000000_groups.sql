-- Group puzzles, v1.1 (docs/Group Puzzles v1.1.md).
--
-- A group is a few people who pool the words they're studying; each day
-- the pool anchors one crossword every member solves on their own copy,
-- and a leaderboard compares them. Everything a member sees is theirs by
-- membership — RLS below — and the words a person contributes are only
-- the headwords they chose to share, never notes or lookup history.
--
-- No Edge Function is needed for the ordinary reads and writes: the app
-- talks to these tables through PostgREST under the caller's JWT. The
-- three things that must be atomic or must bypass RLS are functions.

-- ---------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------

create table public.groups (
  id          uuid primary key default gen_random_uuid(),
  name        text not null check (char_length(name) between 1 and 40),
  owner_id    uuid not null references auth.users (id) on delete cascade,
  invite_code text not null unique,
  created_at  timestamptz not null default now()
);

create table public.group_members (
  group_id     uuid not null references public.groups (id) on delete cascade,
  user_id      uuid not null references auth.users (id) on delete cascade,
  role         text not null default 'member' check (role in ('owner', 'member')),
  display_name text not null check (char_length(display_name) between 1 and 30),
  -- Consent: the person said their study headwords may go into the pool.
  share_words  boolean not null default false,
  joined_at    timestamptz not null default now(),
  primary key (group_id, user_id)
);

create index group_members_by_user on public.group_members (user_id);

-- One row per (member, headword). Cleared when sharing is switched off
-- or the member leaves (cascade).
create table public.group_words (
  group_id   uuid not null,
  user_id    uuid not null,
  headword   text not null check (char_length(headword) between 1 and 40),
  gloss      text,
  updated_at timestamptz not null default now(),
  primary key (group_id, user_id, headword),
  foreign key (group_id, user_id)
    references public.group_members (group_id, user_id) on delete cascade
);

-- The day's puzzle for a group: generated by whichever member opened it
-- first (the app's own generator), published here, played by everyone.
create table public.group_puzzles (
  id           uuid primary key default gen_random_uuid(),
  group_id     uuid not null references public.groups (id) on delete cascade,
  puzzle_date  date not null,
  kind         text not null default 'crossword' check (kind in ('crossword', 'hunt')),
  difficulty   text not null,
  seed         bigint not null,
  grid         jsonb not null,                     -- CrosswordPuzzle.toJson()
  anchors      text[] not null default '{}',      -- the pool words it was built on
  generated_by uuid references auth.users (id) on delete set null,
  created_at   timestamptz not null default now(),
  unique (group_id, puzzle_date, kind)
);

create table public.group_scores (
  puzzle_id    uuid not null references public.group_puzzles (id) on delete cascade,
  user_id      uuid not null references auth.users (id) on delete cascade,
  solved_words integer not null default 0,
  total_words  integer not null default 0,
  completed    boolean not null default false,
  active_ms    integer not null default 0,
  aided        boolean not null default false,
  updated_at   timestamptz not null default now(),
  primary key (puzzle_id, user_id)
);

-- ---------------------------------------------------------------------
-- Membership test the policies share. security definer so it can read
-- group_members without recursing into that table's own policy.
-- ---------------------------------------------------------------------

create or replace function public.is_group_member(p_group uuid)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.group_members
    where group_id = p_group and user_id = auth.uid()
  );
$$;

create or replace function public.is_group_owner(p_group uuid)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.groups where id = p_group and owner_id = auth.uid()
  );
$$;

-- ---------------------------------------------------------------------
-- Row-level security
-- ---------------------------------------------------------------------

alter table public.groups        enable row level security;
alter table public.group_members enable row level security;
alter table public.group_words   enable row level security;
alter table public.group_puzzles enable row level security;
alter table public.group_scores  enable row level security;

create policy "groups: members read"
  on public.groups for select using (public.is_group_member(id));
create policy "groups: owner renames"
  on public.groups for update
  using (owner_id = auth.uid()) with check (owner_id = auth.uid());
create policy "groups: owner deletes"
  on public.groups for delete using (owner_id = auth.uid());
-- Creation goes through group_create(), which also seats the owner.

create policy "members: members read"
  on public.group_members for select using (public.is_group_member(group_id));
create policy "members: own row updates"
  on public.group_members for update
  using (user_id = auth.uid()) with check (user_id = auth.uid() and role = 'member' or public.is_group_owner(group_id));
create policy "members: leave, or owner removes"
  on public.group_members for delete
  using (user_id = auth.uid() and role = 'member' or (public.is_group_owner(group_id) and role = 'member'));
-- Joining goes through group_join().

create policy "words: members read"
  on public.group_words for select using (public.is_group_member(group_id));
create policy "words: own rows"
  on public.group_words for all
  using (user_id = auth.uid()) with check (user_id = auth.uid() and public.is_group_member(group_id));

create policy "puzzles: members read"
  on public.group_puzzles for select using (public.is_group_member(group_id));
-- Publishing goes through group_publish_puzzle().

create policy "scores: members read"
  on public.group_scores for select
  using (exists (select 1 from public.group_puzzles p where p.id = puzzle_id and public.is_group_member(p.group_id)));
create policy "scores: own row"
  on public.group_scores for all
  using (user_id = auth.uid())
  with check (user_id = auth.uid()
    and exists (select 1 from public.group_puzzles p where p.id = puzzle_id and public.is_group_member(p.group_id)));

-- ---------------------------------------------------------------------
-- Functions the app calls (as the signed-in user)
-- ---------------------------------------------------------------------

-- Eight characters, no look-alikes.
create or replace function public.new_invite_code()
returns text
language plpgsql
as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  code text := '';
begin
  for i in 1..8 loop
    code := code || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1);
  end loop;
  return code;
end;
$$;

-- Creates a group and seats the caller as its owner. Returns the group id.
create or replace function public.group_create(p_name text, p_display_name text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_id   uuid;
  v_code text;
begin
  if v_user is null then
    raise exception 'unauthenticated' using errcode = '42501';
  end if;
  if (select count(*) from public.groups where owner_id = v_user) >= 10 then
    raise exception 'too_many_groups' using errcode = 'P0001';
  end if;
  loop
    v_code := public.new_invite_code();
    exit when not exists (select 1 from public.groups where invite_code = v_code);
  end loop;
  insert into public.groups (name, owner_id, invite_code)
    values (trim(p_name), v_user, v_code) returning id into v_id;
  insert into public.group_members (group_id, user_id, role, display_name)
    values (v_id, v_user, 'owner', trim(p_display_name));
  return v_id;
end;
$$;

-- Joins the group behind an invite code. Returns the group id; raises
-- 'invalid_code' / 'group_full'. Rejoining is a no-op.
create or replace function public.group_join(p_code text, p_display_name text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_id   uuid;
begin
  if v_user is null then
    raise exception 'unauthenticated' using errcode = '42501';
  end if;
  select id into v_id from public.groups where invite_code = upper(trim(p_code));
  if v_id is null then
    raise exception 'invalid_code' using errcode = 'P0001';
  end if;
  if (select count(*) from public.group_members where group_id = v_id) >= 12
     and not exists (select 1 from public.group_members where group_id = v_id and user_id = v_user) then
    raise exception 'group_full' using errcode = 'P0001';
  end if;
  insert into public.group_members (group_id, user_id, role, display_name)
    values (v_id, v_user, 'member', trim(p_display_name))
    on conflict (group_id, user_id) do nothing;
  return v_id;
end;
$$;

-- First writer wins: a member who generated today's puzzle offers it; if
-- another member got there first, theirs comes back and the offered one
-- is dropped. Everyone therefore plays the same grid.
create or replace function public.group_publish_puzzle(
  p_group      uuid,
  p_date       date,
  p_kind       text,
  p_difficulty text,
  p_seed       bigint,
  p_grid       jsonb,
  p_anchors    text[]
)
returns public.group_puzzles
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_row  public.group_puzzles;
begin
  if v_user is null or not public.is_group_member(p_group) then
    raise exception 'not_a_member' using errcode = '42501';
  end if;
  insert into public.group_puzzles (group_id, puzzle_date, kind, difficulty, seed, grid, anchors, generated_by)
    values (p_group, p_date, p_kind, p_difficulty, p_seed, p_grid, p_anchors, v_user)
    on conflict (group_id, puzzle_date, kind) do nothing
    returning * into v_row;
  if v_row.id is null then
    select * into v_row from public.group_puzzles
      where group_id = p_group and puzzle_date = p_date and kind = p_kind;
  end if;
  return v_row;
end;
$$;

-- Turning sharing off removes the words at once, not on the next sync.
create or replace function public.group_words_clear_on_unshare()
returns trigger
language plpgsql
as $$
begin
  if old.share_words and not new.share_words then
    delete from public.group_words where group_id = new.group_id and user_id = new.user_id;
  end if;
  return new;
end;
$$;

create trigger group_members_unshare
  after update of share_words on public.group_members
  for each row execute function public.group_words_clear_on_unshare();

grant execute on function public.group_create(text, text) to authenticated;
grant execute on function public.group_join(text, text) to authenticated;
grant execute on function public.group_publish_puzzle(uuid, date, text, text, bigint, jsonb, text[]) to authenticated;
revoke all on function public.new_invite_code() from public, anon, authenticated;
revoke all on function public.is_group_member(uuid) from public, anon;
revoke all on function public.is_group_owner(uuid) from public, anon;
